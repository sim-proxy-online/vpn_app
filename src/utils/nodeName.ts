/**
 * Название сервера для показа. Провайдеры начинают названия с флага-эмодзи («🇷🇺 Автоматический 4G»), а флаг страны
 * в списках уже рисует значок, поэтому в имени он только дублирует. Убирается ровно один эмодзи в самом начале:
 *  • флаг страны — два региональных символа (раньше убирался только первый, и второй оставался квадратиком с буквой);
 *  • флаг региона — чёрный флаг и метки;
 *  • любой другой эмодзи с модификаторами и склейкой.
 * Эмодзи в конце и в середине названия («… ⚡️») остаются — это часть названия. Если после очистки ничего не осталось
 * (название состояло из одного эмодзи), возвращается исходное.
 */
const LEADING_EMOJI = /^(?:\p{Regional_Indicator}{2}|\u{1F3F4}[\u{E0020}-\u{E007F}]+|(?:\p{Extended_Pictographic}|\p{Emoji_Presentation})(?:️|\p{Emoji_Modifier}|‍\p{Extended_Pictographic}️?)*)[\s​]*/u;

export function stripLeadingEmoji(name: string | undefined | null): string {
  const s = (name ?? '').trim();
  const out = s.replace(LEADING_EMOJI, '').trim();
  return out || s;
}
